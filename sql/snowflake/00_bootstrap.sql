-- AtmoSync Week 1 bootstrap. Run as a Snowflake account administrator.
-- This is intentionally idempotent: it does not replace or erase existing data.

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS ATMOSYNC_INGESTOR;
CREATE ROLE IF NOT EXISTS ATMOSYNC_TRANSFORMER;
CREATE ROLE IF NOT EXISTS ATMOSYNC_ANALYST;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS ATMOSYNC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ATMOSYNC;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.RAW;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.REFERENCE;

CREATE TABLE IF NOT EXISTS ATMOSYNC.RAW.RAW_IOT_TELEMETRY (
  EVENT_ID            VARCHAR NOT NULL,
  EVENT_TS            TIMESTAMP_TZ NOT NULL,
  CONTAINER_ID        VARCHAR NOT NULL,
  KAFKA_TOPIC         VARCHAR NOT NULL,
  KAFKA_PARTITION     NUMBER NOT NULL,
  KAFKA_OFFSET        NUMBER NOT NULL,
  PAYLOAD             VARIANT NOT NULL,
  INGESTED_AT         TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT RAW_IOT_TELEMETRY_EVENT_UK UNIQUE (EVENT_ID)
);

USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_INGESTOR;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_INGESTOR;
GRANT USAGE ON SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_INGESTOR;
GRANT INSERT, SELECT ON TABLE ATMOSYNC.RAW.RAW_IOT_TELEMETRY TO ROLE ATMOSYNC_INGESTOR;

GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_TRANSFORMER;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_TRANSFORMER;
GRANT USAGE ON SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_TRANSFORMER;
GRANT SELECT ON TABLE ATMOSYNC.RAW.RAW_IOT_TELEMETRY TO ROLE ATMOSYNC_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ATMOSYNC.ANALYTICS TO ROLE ATMOSYNC_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ATMOSYNC.REFERENCE TO ROLE ATMOSYNC_TRANSFORMER;

GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON SCHEMA ATMOSYNC.ANALYTICS TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON SCHEMA ATMOSYNC.REFERENCE TO ROLE ATMOSYNC_ANALYST;
GRANT SELECT ON TABLE ATMOSYNC.RAW.RAW_IOT_TELEMETRY TO ROLE ATMOSYNC_ANALYST;

